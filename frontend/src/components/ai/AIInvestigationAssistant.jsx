import { useEffect, useState } from 'react'
import api from '../../api/index'
import { API } from '../../api/endpoints'
import { Loader } from '../common/Loader'
import { Badge } from '../common/Badge'
import { Button } from '../common/Button'

export function AIInvestigationAssistant({ investigationId }) {
  const [status, setStatus] = useState(null)
  const [explanation, setExplanation] = useState(null)
  const [report, setReport] = useState(null)
  const [loading, setLoading] = useState(true)
  const [reportLoading, setReportLoading] = useState(false)
  const [error, setError] = useState(null)

  useEffect(() => {
    // Fetch AI provider status
    api
      .get(API.aiStatus)
      .then((res) => setStatus(res.data))
      .catch(() => setStatus({ provider: 'none', available: false, fallback_available: false }))

    // Fetch AI explanation
    api
      .get(API.aiExplain(investigationId))
      .then((res) => setExplanation(res.data))
      .catch(() => setExplanation(null))
      .finally(() => setLoading(false))
  }, [investigationId])

  const handleGenerateReport = async () => {
    setReportLoading(true)
    setError(null)
    try {
      const res = await api.get(API.aiReport(investigationId))
      setReport(res.data)
    } catch (err) {
      setError(err.message || 'Failed to generate report')
    } finally {
      setReportLoading(false)
    }
  }

  if (!status) {
    return null
  }

  const isAvailable = status.available || false
  const provider = status.provider || 'none'
  const fallbackAvailable = status.fallback_available || false
  const fallbackUsed = status.fallback_used || false

  // Determine effective availability: OpenAI OR deterministic fallback
  const effectiveAvailable = isAvailable || fallbackAvailable

  return (
    <section className="card border border-brand/20 p-8">
      <h2 className="font-display font-semibold text-text-primary mb-6">AI Investigation Assistant</h2>

      {/* Provider Status */}
      <div className="flex items-center justify-between mb-6">
        <div>
          <h3 className="font-display font-bold text-text-primary mb-1">Provider Status</h3>
          <p className="text-xs text-text-secondary">
            AI explanations are generated by {provider.toUpperCase()}.
            {fallbackUsed && ' (deterministic fallback — OpenAI unavailable)'}
          </p>
        </div>
        <Badge
          variant={effectiveAvailable ? 'low' : 'default'}
          className={`text-xs px-3 py-1 ${fallbackUsed ? 'bg-brand/10 border-brand/20 text-brand' : ''}`}
        >
          {!isAvailable && fallbackAvailable ? 'FALLBACK' : isAvailable ? (fallbackUsed ? 'FALLBACK' : 'AVAILABLE') : 'UNAVAILABLE'}
        </Badge>
      </div>

      {/* AI Explanation */}
      <div className="mb-8">
        <h3 className="font-display font-bold text-text-primary mb-3">AI-Generated Explanation</h3>
        {loading && <Loader className="w-auto" />}
        {!loading && explanation && explanation.data && (
          <div className="card-elevated border border-border-color rounded-lg p-6 font-mono-tech text-sm text-text-secondary whitespace-pre-wrap break-words">
            {explanation.data.summary || 'No explanation available.'}
          </div>
        )}
        {!loading && explanation && !explanation.data && (
          <p className="text-sm text-text-secondary">No AI explanation available.</p>
        )}
        {!loading && !explanation && !error && (
          <p className="text-sm text-text-secondary">No AI explanation available.</p>
        )}
        {!loading && !explanation && error && (
          <p className="text-sm text-text-secondary">AI explanation unavailable.</p>
        )}
      </div>

      {/* AI Report */}
      <div className="mb-8">
        <h3 className="font-display font-bold text-text-primary mb-3">Investigation Report</h3>
        <Button
          variant="secondary"
          onClick={handleGenerateReport}
          disabled={reportLoading}
        >
          {reportLoading ? 'Generating...' : 'Generate AI Report'}
        </Button>
        {report && report.data && (
          <div className="mt-4 p-4 card-elevated border border-border-color font-mono-tech text-sm text-text-secondary whitespace-pre-wrap break-words">
            {report.data.summary || report.data.report || 'No report generated.'}
          </div>
        )}
        {report && !report.data && (
          <p className="text-sm text-text-secondary">No report generated.</p>
        )}
        {error && (
          <p className="text-sm text-text-secondary mt-2">{error}</p>
        )}
      </div>

      {/* Limitations */}
      <div className="p-4 card-elevated border border-border-color">
        <h3 className="font-display font-bold text-text-primary mb-3">Important Limitations</h3>
        <ul className="text-sm text-text-secondary space-y-2 list-disc list-inside">
          <li>
            AI-generated explanations are interpretations of existing evidence and do not override
            the authoritative backend risk score.
          </li>
          <li>
            When OpenAI is unavailable, explanations use deterministic fallback logic.
          </li>
          <li>
            AI never invents findings, entities, URLs, or evidence. All content is grounded in
            submitted investigation data.
          </li>
        </ul>
      </div>
    </section>
  )
}